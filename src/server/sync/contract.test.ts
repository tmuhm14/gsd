import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { z } from "zod";
import { BUCKETS, ENERGY_LEVELS, ITEM_KINDS } from "@/lib/gtd";
import { MAX_PULL_LIMIT } from "@/server/sync/service";

/**
 * Cross-stack contract test.
 *
 * `test-fixtures/swift-sync-payload.json` is written by the macOS app's own
 * encoder (see SyncContractTests.swift). The two apps share no types, so a
 * renamed field or a reformatted date would otherwise only show up as a 400
 * during a real sync. This validates the Swift client's actual output against
 * the schema this endpoint enforces.
 *
 * Kept byte-identical to the schema in src/app/api/sync/route.ts — if that one
 * changes, this must too, and the fixture must be regenerated by running the
 * macOS test suite.
 */
const isoDate = z.iso.datetime({ offset: true });

const syncItemSchema = z.object({
  id: z.uuid(),
  body: z.string().max(200_000),
  kind: z.enum(ITEM_KINDS),
  bucket: z.enum(BUCKETS),
  projectId: z.uuid().nullable(),
  dueDate: isoDate.nullable(),
  deferDate: isoDate.nullable(),
  energy: z.enum(ENERGY_LEVELS).nullable(),
  waitingOn: z.string().max(200).nullable(),
  pinned: z.boolean(),
  createdAt: isoDate,
  updatedAt: isoDate,
  completedAt: isoDate.nullable(),
  deletedAt: isoDate.nullable(),
});

const requestSchema = z.object({
  since: z.number().int().min(0).default(0),
  limit: z.number().int().min(1).max(MAX_PULL_LIMIT).optional(),
  changes: z.array(syncItemSchema).max(MAX_PULL_LIMIT).default([]),
});

const payload: unknown = JSON.parse(
  readFileSync("test-fixtures/swift-sync-payload.json", "utf8"),
);

describe("the macOS client's payload", () => {
  it("passes the endpoint's validation", () => {
    const parsed = requestSchema.safeParse(payload);
    if (!parsed.success) {
      throw new Error(
        `Swift payload rejected:\n${JSON.stringify(parsed.error.issues, null, 2)}`,
      );
    }
    expect(parsed.success).toBe(true);
  });

  it("covers the full, sparse and deleted cases", () => {
    const parsed = requestSchema.parse(payload);
    expect(parsed.changes.length).toBeGreaterThanOrEqual(3);

    // Every nullable field populated on at least one item…
    expect(parsed.changes.some((item) => item.dueDate !== null)).toBe(true);
    expect(parsed.changes.some((item) => item.energy !== null)).toBe(true);
    expect(parsed.changes.some((item) => item.waitingOn !== null)).toBe(true);
    expect(parsed.changes.some((item) => item.completedAt !== null)).toBe(true);
    // …and null on at least one other, so both encodings are exercised.
    expect(parsed.changes.some((item) => item.dueDate === null)).toBe(true);
    // A tombstone, which is how deletes travel.
    expect(parsed.changes.some((item) => item.deletedAt !== null)).toBe(true);
  });

  it("includes an item in the newest bucket", () => {
    // Proves the server's enum and the client's vocabulary still agree after
    // a bucket is added on one side.
    const parsed = requestSchema.parse(payload);
    expect(parsed.changes.some((item) => item.bucket === "quick")).toBe(true);
  });

  it("sends lowercase UUIDs, which Postgres expects", () => {
    const parsed = requestSchema.parse(payload);
    for (const item of parsed.changes) {
      expect(item.id).toBe(item.id.toLowerCase());
    }
  });
});
